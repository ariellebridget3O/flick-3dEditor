skipped = []
for name in CONSTS + FNS:
    f = f'{D}/fn_{name}.js'
    if not os.path.exists(f):
        skipped.append(name); continue
    body = [l for l in open(f).read().split('\n') if not l.startswith('//') and l.strip()]
    parts.append('\n// ==== %s ====\n%s' % (name, '\n'.join(body)))

exports = ',\n  '.join(FNS + ['VWt', 'pie', 'XCe', 'Mtt', 'Lzt'])
parts.append(f"""
export {{
  {exports}
}};
""")
open('/home/z/my-project/scripts/oracle/reference.mjs', 'w').write(''.join(parts))
print(f'reference.mjs written: {len(FNS)+3} exports; skipped (missing files): {skipped}')
